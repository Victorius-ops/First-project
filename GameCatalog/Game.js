export class Game {
    constructor(ID, title, genre, price, platform, rating, year, description, isFavorite) {
        this.ID = ID;
        this.title = title;
        this.genre = genre;
        this.price = price;
        this.platform = platform;
        this.rating = rating;
        this.year = year;
        this.description = description;
        this.isFavorite = isFavorite;
    }
}